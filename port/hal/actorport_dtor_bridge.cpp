// ACTORPORT -- the link bridge for the two-arm destructor spelling.
//
// include/ now spells every actor-family destructor as two plain virtuals
// under _MSC_VER (Destructor1 = ROM slot 16, Destructor0 = slot 17) plus a
// non-virtual ~X() declaration, so MSVC numbers the vtable the way mwccarm
// does and the forty dispatch sites lane VTABLE measured stop asking for the
// wrong slot.  Two link-time consequences follow, and this file answers both
// with the tree's own /alternatename mechanism.  Neither is a revert.
//
// 1. ??1X@@UAE@XZ.  src/_ZN<X>D1Ev.cpp includes the real header, so it used
//    to define the VIRTUAL mangle; it now defines ??1X@@QAE@XZ.  Every face
//    generated against the old name -- faces_sync_gen.cpp, the CPPD1 shadows
//    in hal/dtor_faces_cpp.cpp -- still asks for the virtual one.  The alias
//    points it at the same body.  Same __thiscall receiver, no stack args on
//    either side, so the alias is ABI-exact.
//
// 2. ?Destructor1@X@@UAEXXZ and ?Destructor0@X@@UAEXXZ.  A TU that emits a
//    COMPILER vtable for X now needs an address for each of the two slots.
//    NOTHING DISPATCHES THROUGH THAT TABLE: the port fills ROM-shaped tables
//    (hal/actor_classes*.cpp) and every live dispatch goes through those, which
//    is why hal/dtor_store_guard.py is allowed to call MSVC's transient vptr
//    store inert.  So these two only have to LINK.  Destructor1 is aliased to
//    the class's own complete-object destructor, which is what ROM slot 16
//    holds.  Destructor0 is aliased to a shared trap: the deleting half's free
//    is per class, and inventing one generic body would be a guess.  If the
//    trap ever fires it means something really did dispatch the compiler table,
//    which is a finding, not a crash to paper over.
//
// Generated, not hand-written: out/ACTORPORT/genbridge.py from the linker's own
// unresolved-symbol list.  Regenerate rather than edit.

#include <stdio.h>
#include <stdlib.h>

extern "C" void __fastcall actorport_dtor_slot_trap(void *self, void *unused)
{
    (void)unused;
    fprintf(stderr, "ACTORPORT TRAP: a COMPILER vtable destructor slot was "
                    "dispatched on %p. The port dispatches ROM-shaped tables; "
                    "reaching this means one object is running MSVC's own "
                    "table. Report it, do not silence it.\n", self);
    abort();
}

